import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const BASE=`http://127.0.0.1:${process.env.TEST_PORT||4182}`;
try {
  const p=await browser.newPage({viewport:{width:1440,height:1100}}),errors=[];
  p.on('pageerror',e=>errors.push(e.message));
  await p.addInitScript(()=>{Math.random=()=>.5;});
  await p.goto(BASE,{waitUntil:'networkidle'});await p.waitForTimeout(2700);
  const world=()=>p.evaluate(()=>JSON.parse(localStorage.getItem('minefield-zen-v1')));
  const clear=async()=>{
    await p.locator('.tile').nth(40).click();
    const w=await world(),r=w.expeditions.routes[w.current],b=r.stops[r.cursor].board;
    const safe=b.cells.flatMap((c,i)=>!c.mine?[i]:[]);
    for(const i of safe)if(await p.locator('.tile').nth(i).isEnabled())await p.locator('.tile').nth(i).click();
    await p.locator('.result-card').waitFor();
  };
  const advance=()=>p.getByRole('button',{name:'Continue expedition',exact:true}).click();
  await p.locator('.mode-card-zen').click();
  await p.getByRole('button',{name:'Open branch map',exact:true}).click();
  await p.getByRole('button',{name:'Begin expedition in this limb',exact:true}).click();
  assert.equal(await p.locator('.atlas-node').count(),7);
  assert.equal(await p.locator('.expedition-route').count(),0,'no text route above board');
  await p.getByRole('button',{name:'Close map',exact:true}).click();
  await p.getByRole('button',{name:/Inventory ·/}).click();
  assert.ok(await p.getByLabel('Branch inventory',{exact:true}).isVisible());
  await p.getByRole('checkbox',{name:/Use a Return Totem/}).uncheck();
  await p.getByRole('button',{name:'Close inventory',exact:true}).click();
  await p.getByRole('button',{name:'Open branch map',exact:true}).click();
  await p.getByRole('button',{name:'Minefield · stop 1 · available',exact:true}).click();
  await p.getByRole('button',{name:'Enter minefield',exact:true}).click();
  await clear();let w=await world();assert.equal(w.expeditions.coins,20);
  assert.equal(w.areas['0'].children.length,0,'one board is not a completed expedition');
  await advance();
  await p.getByRole('button',{name:'Trading post · stop 2 · available',exact:true}).click();
  const survey=p.locator('.expedition-shop article').filter({has:p.getByRole('heading',{name:'Survey Lantern',exact:true})});
  await survey.getByRole('button',{name:'Buy · 20 coins',exact:true}).click();
  w=await world();assert.equal(w.expeditions.surveyCharges,2);assert.equal(w.expeditions.coins,0);
  await p.getByRole('button',{name:'Close map',exact:true}).click();
  await p.getByRole('button',{name:/Inventory ·/}).click();
  const owned=p.locator('.expedition-inventory article').filter({has:p.getByRole('heading',{name:'Survey Lantern',exact:true})});
  await owned.getByRole('button',{name:'Equip',exact:true}).click();
  await p.getByRole('button',{name:'Close inventory',exact:true}).click();
  await p.getByRole('button',{name:'Open branch map',exact:true}).click();
  await p.getByRole('button',{name:'Leave trading post',exact:true}).click();
  await p.getByRole('button',{name:'Danger route · stop 3 · available',exact:true}).click();
  await p.getByRole('button',{name:'Enter minefield',exact:true}).click();
  await p.locator('.tile').nth(40).click();
  await p.getByRole('button',{name:'Survey Lantern · 2 charges',exact:true}).click();
  assert.ok(await p.locator('.tile.scanned').count()>0);
  w=await world();assert.equal(w.expeditions.surveyCharges,1);
  let r=w.expeditions.routes[w.current],b=r.stops[r.cursor].board;
  for(const i of b.cells.flatMap((c,i)=>!c.mine?[i]:[]))if(await p.locator('.tile').nth(i).isEnabled())await p.locator('.tile').nth(i).click();
  await p.locator('.result-card').waitFor();await advance();
  await p.getByRole('button',{name:'Bank shelter · stop 4 · available',exact:true}).click();
  await p.getByRole('button',{name:'Bank all carried coins',exact:true}).click();
  w=await world();assert.equal(w.expeditions.bank,35);assert.equal(w.expeditions.coins,0);
  await p.getByRole('button',{name:'Continue from shelter',exact:true}).click();
  await p.getByRole('button',{name:'Boss gate · stop 5 · available',exact:true}).click();
  assert.match(await p.locator('.expedition-boss').innerText(),/Phase 1 \/ 2/);
  await p.getByRole('button',{name:'Start announced phase 1',exact:true}).click();await clear();
  w=await world();assert.equal(w.expeditions.coins,45);assert.equal(w.areas['0'].children.length,0);
  await advance();assert.match(await p.locator('.expedition-boss').innerText(),/Phase 2 \/ 2/);
  await p.getByRole('button',{name:'Start announced phase 2',exact:true}).click();
  await p.locator('.tile').nth(40).click();w=await world();r=w.expeditions.routes[w.current];b=r.stops[r.cursor].board;
  await p.locator('.tile').nth(b.cells.findIndex(c=>c.mine)).click();
  await p.locator('.result-card').waitFor();
  assert.match(await p.locator('.result-card').innerText(),/You dropped some money!/);
  assert.equal(await p.locator('.tile.exploded.mine-visible').count(),1);
  w=await world();assert.equal(w.expeditions.bank,35);assert.equal(w.expeditions.coins,20);
  assert.equal(w.expeditions.drops[0].amount,25);
  // Restart must preserve the actual mine-hit screen, penalty and pending recovery.
  await p.reload({waitUntil:'networkidle'});await p.waitForTimeout(2700);
  await p.locator('.mode-card-zen').click();await p.locator('.result-card').waitFor();
  assert.match(await p.locator('.result-card').innerText(),/You dropped some money!/);
  await p.getByRole('button',{name:'See the board',exact:true}).click();
  await p.locator('.expedition-hud').getByRole('button',{name:'Continue after the mine hit',exact:true}).click();
  w=await world();assert.equal(w.expeditions.coins,20);assert.equal(w.expeditions.bank,35);
  assert.equal(w.expeditions.routes['0'].attempt,1);
  assert.equal(w.expeditions.drops[0].checkedAttempt,1);
  assert.equal(w.expeditions.pendingLoss,undefined);
  await p.getByRole('button',{name:'Open branch map',exact:true}).click();
  // Replay the failed route: old board rewards stay claimed, but the previously
  // uncleared final boss phase still pays and unlocks the next limb.
  await p.getByRole('button',{name:'Enter minefield',exact:true}).click();await clear();await advance();
  await p.getByRole('button',{name:'Leave trading post',exact:true}).click();
  await p.getByRole('button',{name:'Enter minefield',exact:true}).click();await clear();await advance();
  await p.getByRole('button',{name:'Continue from shelter',exact:true}).click();
  await p.getByRole('button',{name:'Start announced phase 1',exact:true}).click();await clear();await advance();
  await p.getByRole('button',{name:'Start announced phase 2',exact:true}).click();await clear();
  w=await world();assert.equal(w.expeditions.coins,65,'only the new final phase pays during replay');
  assert.equal(w.expeditions.bank,35);assert.equal(w.areas['0'].children.length,2);
  await p.getByRole('button',{name:'Grow the next limb',exact:true}).click();
  await p.getByRole('button',{name:'Open branch map',exact:true}).click();
  await p.getByRole('button',{name:'Begin expedition in this limb',exact:true}).click();
  w=await world();assert.equal(w.current,'0.0');assert.equal(w.expeditions.routes['0.0'].depth,1);
  assert.equal(w.expeditions.bank,35);assert.equal(w.expeditions.inventory.totem,1,'new limbs do not duplicate the starter kit');
  await p.getByRole('button',{name:'Close map',exact:true}).click();
  await p.setViewportSize({width:390,height:844});
  await p.getByRole('button',{name:/Inventory ·/}).click();
  assert.ok(await p.getByLabel('Branch inventory',{exact:true}).isVisible());
  assert.equal(await p.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'inventory fits mobile width');
  assert.deepEqual(errors,[]);
  console.log('Expedition UI passed: opt-in route, real clears, shop purchase, equipping/using charged ability, banking, announced boss phases, money-drop notice, visible hit, restart-safe loss/return and mobile inventory.');
}finally{await browser.close();}
